"""Walking-inspect steel and air cues, timed from the authored clip and the
measured source envelopes (no listening). Writes the runtime cue table header.

- Air: the hammer's own swing whoosh, raised in pitch for the faster turn; its
  loudest 10 ms lands just after release, at the highest turn rate.
- Steel snap: bright steel ring (melee block 02) whose attack lands on the
  release, ringing on through the turn.
- Steel catch: heavy steel strike (forge hammer) whose attack lands when the
  palms clamp the still-turning shaft.
Levels are set relative to the whoosh's loudest 10 ms after volume/pitch.
"""
import json,math
from pathlib import Path

P=Path(__file__).resolve().parent;ANIM=P.parent;ROOT=P.parents[3]
profile=json.loads((P/'source_profile.json').read_text())
timeline=json.loads((ANIM/'authored.json').read_text())['phases_seconds']
RELEASE=timeline['right_flick'][1];CATCH=timeline['catch_absorb'][0]
ASSETS={'hammer_swing_air':'/Game/Weapons/SteelWarhammer20261014/NormalSwingAudioV1/S_Warhammer_NormalSwing.S_Warhammer_NormalSwing',
        'steel_block_02':'/Game/Audio/MeleeBlock20260927/S_MeleeBlock_02.S_MeleeBlock_02',
        'forge_anvil':'/Game/Props/ForgeInteraction20260927/SW_ForgeHammerImpact.SW_ForgeHammerImpact'}
AIR_VOLUME=.30
# (source, anchor event, align on 'loudest' or 'onset', offset s, pitch, level dB relative to the whoosh)
# 2026-10-15: user kept only the air whoosh; the two steel layers were removed.
DESIGN=[('hammer_swing_air','release','loudest',.035,1.35,0.)]
REMOVED=[('steel_block_02','release','onset',0.,1.30,-8.),('forge_anvil','catch','onset',0.,1.20,-5.)]
air_level=profile['hammer_swing_air']['loudest_10ms_dbfs']+20*math.log10(AIR_VOLUME)
cues=[]
for source,anchor,align,offset,pitch,relative in DESIGN:
    p=profile[source];event=RELEASE if anchor=='release' else CATCH
    lead=(p['loudest_10ms_at_s'] if align=='loudest' else p['onset_minus12db_at_s'])/pitch
    volume=AIR_VOLUME if source=='hammer_swing_air' else 10**((air_level+relative-p['loudest_10ms_dbfs'])/20)
    cues.append({'source':source,'asset':ASSETS[source],'anchor':anchor,'event_seconds':event,'aligned':align,
        'trigger_seconds':round(max(0.,event+offset-lead),4),'volume':round(min(1.,volume),3),'pitch':pitch,
        'played_seconds':round(p['seconds']/pitch,3)})
lines=['#pragma once','#include "CoreMinimal.h"',
 '// Generated by SourceAssets/SteelWarhammer20261014/InspectWalkSpeedV3/Audio/author_cues.py from the',
 '// walking inspect timeline and measured source envelopes. Seconds are A_Warhammer_InspectWalk clip time.',
 'namespace WarhammerInspectWalkCues','{',
 'struct FCue { const TCHAR* Sound; float Seconds; float Volume; float Pitch; };',
 'inline constexpr FCue Cues[]={']
notes={'hammer_swing_air':'air: swing whoosh peaks at the highest turn rate','steel_block_02':'steel: bright ring on the release snap',
       'forge_anvil':'steel: heavy strike as the palms clamp the turning shaft'}
for c in cues:lines.append('    {TEXT("%s"),%.4ff,%.3ff,%.2ff}, // %s'%(c['asset'],c['trigger_seconds'],c['volume'],c['pitch'],notes[c['source']]))
lines+=['};','}','']
(ROOT/'Source/FPSGAME/Production/WarhammerInspectWalkCues.h').write_text('\n'.join(lines),encoding='utf-8')
receipt={'release_seconds':RELEASE,'catch_seconds':CATCH,'air_reference_level_dbfs':air_level,'cues':cues,
    'removed_by_user':[r[0] for r in REMOVED],'listened':False,'runtime_tested':False}
(P/'cues.json').write_text(json.dumps(receipt,indent=2),encoding='utf-8')
print('WARHAMMER_INSPECT_WALK_CUES '+json.dumps(receipt))
