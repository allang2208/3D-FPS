"""Match the actual V2 gait samples, including stance/swing direction."""
import json, math
from pathlib import Path

ROOT = Path(__file__).parent
clips = json.loads((ROOT/'clip_poses.json').read_text())

def sub(a,b): return [x-y for x,y in zip(a,b)]
def dot(a,b): return sum(x*y for x,y in zip(a,b))
def relative(p,n): return sub(p[n]['position'],p['Hips']['position'])
def velocity(poses,i,n):
    return sub(relative(poses[(i+1)%len(poses)],n),relative(poses[(i-1)%len(poses)],n))

def cost(a,b,i,j):
    score = 0
    for n,w in [('LeftFoot',3),('RightFoot',3),('LeftLeg',.6),('RightLeg',.6)]:
        d = sub(relative(a[i],n),relative(b[j],n))
        score += w*dot(d,d)
        if n.endswith('Foot'):
            va,vb = velocity(a,i,n),velocity(b,j,n)
            length = math.sqrt(dot(va,va)*dot(vb,vb))
            if length > 1e-8: score += .03*(1-max(-1,min(1,dot(va,vb)/length)))
    return score

header = ['// Generated by transitions/build_gait_map.py from the saved KhaimeraV2 poses.',
          '// One target sample (60 Hz) per source sample. Only used when changing gait.',
          '#pragma once', 'namespace Mutant3GaitPhases', '{']
report = {}
for source,target in [('FeralRun','FeralSprint'),('FeralSprint','FeralRun')]:
    a,b = clips[source][:-1],clips[target][:-1]
    frames = [min(range(len(b)),key=lambda j:cost(a,b,i,j)) for i in range(len(a))]
    name = 'RunToSprint' if source == 'FeralRun' else 'SprintToRun'
    header.append('    inline constexpr uint8 '+name+'[] = {')
    for i in range(0,len(frames),16): header.append('        '+', '.join(map(str,frames[i:i+16]))+',')
    header.append('    };')
    report[name] = {'source_frames':len(a),'target_frames':len(b),'target_sample_for_source':frames,
                   'mean_matched_cost':sum(cost(a,b,i,j) for i,j in enumerate(frames))/len(a),
                   'mean_unsynchronized_cost':sum(cost(a,b,i,j) for i in range(len(a)) for j in range(len(b)))/(len(a)*len(b))}
header.extend(['}', ''])
(ROOT.parents[2]/'Source/FPSGAME/Monsters/Mutant3GaitPhases.inl').write_text('\n'.join(header),encoding='utf-8')
(ROOT/'gait_mapping.json').write_text(json.dumps(report,indent=2),encoding='utf-8')
for name,data in report.items(): print(name,'samples',data['source_frames'],'cost',round(data['mean_unsynchronized_cost'],4),'->',round(data['mean_matched_cost'],4))
