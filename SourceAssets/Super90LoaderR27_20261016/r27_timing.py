"""R27 push clock: R25's 'align, then accelerate in' rhythm, with a cleaner drive.

The user preferred R25 over R26: the deep slowdown after the dock reads as
aligning and the contrast to the drive reads as pushing in. R27 therefore keeps
R25's alignment span (pace 86-104, same Hermite, same 30 % split) unchanged and
redesigns only the drive (104-116):
- R25's drive peaked at pace 110, dipped at the 113 knot (1.73 -> 1.46 -> 1.62),
  and braked over three frames, so the last push stuttered and landed softly.
- R27 accelerates monotonically into the seat (peak just before pace 115) and
  brakes within the final frame, so the push drives home and stops on the seat.
Same API as r26_timing: KNOTS, source_frame, pace_frame, slope, header().
"""
import numpy as np
from scipy.interpolate import PchipInterpolator
from scipy.optimize import brentq

SPLIT = 92.502451001
BEGIN, ALIGN, SEAT = 86., 104., 116.
SOURCE_SEAT = 110.
EXTRA = SEAT - SOURCE_SEAT
R25_ALIGN = ((86., 86., 1.), (104., SPLIT, .620325796))     # user-approved alignment span
# Slope d(source)/d(pace). The installed pusher slows over source 104-110, so the
# slope keeps rising late to make the perceived push accelerate into the seat.
DRIVE = [(104, .620325796), (105, .76), (106, .90), (107, 1.05), (108, 1.21), (109, 1.38), (110, 1.56),
         (111, 1.74), (112, 1.96), (113, 2.17), (114, 2.33), (114.6, 2.40), (115.3, 2.10), (116, 1.00)]


def _hermite(p, a, b):
    (pa, sa, ma), (pb, sb, mb) = a, b
    span = pb - pa; t = (p - pa) / span; t2, t3 = t * t, t * t * t
    return ((2 * t3 - 3 * t2 + 1) * sa + (t3 - 2 * t2 + t) * span * ma
            + (-2 * t3 + 3 * t2) * sb + (t3 - t2) * span * mb)


def _drive(scale):
    pts = [(p, v * (scale if ALIGN < p < SEAT else 1.)) for p, v in DRIVE]
    return PchipInterpolator(*np.array(pts, float).T)


def _area(v):
    x = np.linspace(ALIGN, SEAT, 6001)
    return float(np.trapezoid(v(x), x))


scale = brentq(lambda s: _area(_drive(s)) - (SOURCE_SEAT - SPLIT), .3, 3.)
VELOCITY = _drive(scale)
_fine = np.linspace(ALIGN, SEAT, 24001)
_integral = SPLIT + np.r_[0., np.cumsum((VELOCITY(_fine[1:]) + VELOCITY(_fine[:-1])) * .5 * np.diff(_fine))]
# Alignment: R25's own span (identical curve); drive: one knot per pace frame.
KNOTS = [R25_ALIGN[0], R25_ALIGN[1]]
KNOTS += [(float(p), float(np.interp(p, _fine, _integral)), float(VELOCITY(p))) for p in np.arange(ALIGN + 1., SEAT)]
KNOTS += [(SEAT, SOURCE_SEAT, 1.)]


def source_frame(pace):
    """Exactly the runtime Hermite in Super90LoaderPushTiming.h, in frames."""
    if pace <= BEGIN:
        return pace
    if pace >= SEAT:
        return pace - EXTRA
    for a, b in zip(KNOTS, KNOTS[1:]):
        if pace <= b[0]:
            return _hermite(pace, a, b)
    return pace - EXTRA


def slope(pace, h=1e-3):
    return (source_frame(pace + h) - source_frame(pace - h)) / (2 * h)


def pace_frame(source):
    if source <= BEGIN:
        return source
    if source >= SOURCE_SEAT:
        return source + EXTRA
    return float(brentq(lambda p: source_frame(p) - source, BEGIN, SEAT, xtol=1e-9))


def header():
    lines = ['#pragma once', '#include "CoreMinimal.h"', '',
             '// Generated by Super90LoaderR27_20261016/author_timing.py.',
             '// R27 keeps R25\'s alignment (30% of the stroke slowly by pace 104, the',
             '// deep slowdown after the dock reads as aligning) and redesigns the drive:',
             '// one monotone acceleration into the seat, braking only in the last frame.',
             '// This clock is shared by poses, grip profiles, props, audio and camera.',
             'namespace Super90LoaderPushTiming', '{',
             'inline constexpr float ExtraDuration = 6.f / 60.f;',
             'inline float SourceTime(float PaceTime)', '{',
             '    const float Frame = PaceTime * 60.f;',
             '    if (Frame <= 86.f) return PaceTime;',
             '    if (Frame >= 116.f) return PaceTime - ExtraDuration;',
             '    struct FKnot { float Pace; float Source; float Slope; };',
             '    static constexpr FKnot Knots[] = {']
    lines += [f'        {{{p:.9f}f, {s:.9f}f, {m:.9f}f}},' for p, s, m in KNOTS]
    lines += ['    };',
              '    for (int32 I = 1; I < UE_ARRAY_COUNT(Knots); ++I)', '    {',
              '        const FKnot& A = Knots[I - 1];', '        const FKnot& B = Knots[I];',
              '        if (Frame > B.Pace) continue;',
              '        const float Span = B.Pace - A.Pace;',
              '        const float T = (Frame - A.Pace) / Span;',
              '        const float T2 = T * T, T3 = T2 * T;',
              '        return ((2.f * T3 - 3.f * T2 + 1.f) * A.Source',
              '            + (T3 - 2.f * T2 + T) * Span * A.Slope',
              '            + (-2.f * T3 + 3.f * T2) * B.Source',
              '            + (T3 - T2) * Span * B.Slope) / 60.f;',
              '    }', '    return PaceTime - ExtraDuration;', '}', '}', '']
    return '\n'.join(lines)
