"""Hand traces in the enlarged resting-state reference, looking along +Y."""
import numpy as np

# Chart = 1.6x crop of source left panel, with origin at original pixel (100,210).
CENTER = 413.6
PIXELS_PER_CM = 31.3
COLLAR_BASE = 364.
ATLAS_SIZE = 2048
CHART_SCALE = 2.44
CHART_BORDER = 16.


def front_uv(x, y):
    return ((CHART_BORDER+x*CHART_SCALE)/ATLAS_SIZE,
            1-(CHART_BORDER+y*CHART_SCALE)/ATLAS_SIZE)


def model_point(x, y, depth):
    return ((x-CENTER)/PIXELS_PER_CM*.01, depth*.01,
            (-5+(COLLAR_BASE-y)/PIXELS_PER_CM)*.01)


def bezier(points, steps=32):
    """Joined cubic spans; control points are in drawing space."""
    points = np.asarray(points, dtype=float)
    spans = []
    for i in range(0, len(points)-1, 3):
        a,b,c,d = points[i:i+4]
        t = np.linspace(0, 1, steps+1)[:, None]
        sampled = (1-t)**3*a + 3*(1-t)**2*t*b + 3*(1-t)*t*t*c + t**3*d
        spans.append(sampled if not i else sampled[1:])
    return np.vstack(spans)


