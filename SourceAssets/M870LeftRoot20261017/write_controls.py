"""Bake only the fixed shoulder-rim controls; no mesh reads at runtime."""
from analyze import *

rows=[]
for key,data in [('shirt',S),('skin',K)]:
    inverse={n:np.linalg.inv(mat(data['rest'][n])) for n in ('upperarm_l','clavicle_l')}
    for i in G[key]['ids']:
        p=np.r_[G[key]['v'][i],1.]
        rows.append({'source':key,'vertex':int(i),'upper':(inverse['upperarm_l']@p)[:3].tolist(),
                     'clavicle':(inverse['clavicle_l']@p)[:3].tolist(),'upper_weight':data['weights'][i].get('upperarm_l',0.)})
def vec(v):return 'FVector3f('+', '.join(f'{x:.10f}f' for x in v)+')'
text='// Generated by SourceAssets/M870LeftRoot20261017/write_controls.py.\n'
text+='// Current V9 skin and Super90-bound chainmail: the complete left shoulder rims.\n'
text+='// Bone-local coordinates include the native scale-100 reference binding.\n'
text+='namespace M870ArmOpening\n{\nstruct FControl { FVector3f Upper, Clavicle; float UpperWeight; };\n'
text+='static const FControl Controls[] =\n{\n'
for row in rows:text+='    {'+vec(row['upper'])+', '+vec(row['clavicle'])+f', {row["upper_weight"]:.10f}f'+'},\n'
text+='};\n}\n'
(O.parents[1]/'Source/FPSGAME/Weapons/M870ArmOpeningControls.inl').write_text(text,encoding='utf-8')
(O/'opening_controls.json').write_text(json.dumps({'controls':rows,'sources':{'skin':K['sha256'],'shirt':S['sha256']}},indent=2))
print('M870_OPENING_CONTROLS_WRITTEN',len(rows))
