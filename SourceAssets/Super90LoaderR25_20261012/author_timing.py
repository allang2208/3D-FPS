"""Keep accepted poses; author a shared slow-align / fast-drive source clock."""
import json
from pathlib import Path
import numpy as np
from scipy.interpolate import CubicHermiteSpline, PchipInterpolator
from scipy.optimize import brentq

O = Path(__file__).parent
P = O.parents[1]
source = O.parent / 'Super90LoaderR21_20261010/source_poses.json'
poses = json.loads(source.read_text())
# R21's rigid gun/arms response preserves this gun-relative travel; the later
# wrist/grasp and R24 bolt corrections preserve the accepted push positions.
rows = poses['normal'][86:111]
points = np.array([(np.linalg.inv(row['WPN_root']) @ np.array(row['hand_l']))[:3, 3] for row in rows])
axis = points[-1] - points[0]
progress = (points - points[0]) @ axis / (axis @ axis)
split_source = float(np.interp(.30, progress, np.arange(86, 111)))
# 18 frames for the first 30% of travel, 12 for the remaining 70%.
# The fast drive peaks before the last three frames, then settles into the
# original release at 1x. Extra six frames shift later actions without retiming them.
pace = [86., 104., 113., 116.]
frames = [86., split_source, 105.6, 110.]
slopes = PchipInterpolator(pace, frames).derivative()(pace)
slopes[0] = slopes[-1] = 1.
curve = CubicHermiteSpline(pace, frames, slopes)

def runtime_frame(frame):
    if frame <= 86:
        return frame
    if frame >= 110:
        return frame + 6
    return float(brentq(lambda t: float(curve(t)) - frame, 86, 116))

header = ['#pragma once', '#include "CoreMinimal.h"', '',
    '// Generated by Super90LoaderR25_20261012/author_timing.py.',
    '// Preserve the full stroke: first 30% aligns slowly, final 70% drives faster.',
    '// This clock is shared by poses, grip profiles, props, audio and camera.',
    'namespace Super90LoaderPushTiming', '{',
    'inline constexpr float ExtraDuration = 6.f / 60.f;',
    'inline float SourceTime(float PaceTime)', '{',
    '    const float Frame = PaceTime * 60.f;',
    '    if (Frame <= 86.f) return PaceTime;',
    '    if (Frame >= 116.f) return PaceTime - ExtraDuration;',
    '    struct FKnot { float Pace; float Source; float Slope; };',
    '    static constexpr FKnot Knots[] = {']
header += [f'        {{{x:.9f}f, {y:.9f}f, {m:.9f}f}},' for x, y, m in zip(pace, frames, slopes)]
header += ['    };',
    '    for (int32 I = 1; I < UE_ARRAY_COUNT(Knots); ++I)', '    {',
    '        const FKnot& A = Knots[I - 1];', '        const FKnot& B = Knots[I];',
    '        if (Frame > B.Pace) continue;',
    '        const float Span = B.Pace - A.Pace;',
    '        const float T = (Frame - A.Pace) / Span;',
    '        const float T2 = T * T, T3 = T2 * T;',
    '        return ((2.f * T3 - 3.f * T2 + 1.f) * A.Source',
    '            + (T3 - 2.f * T2 + T) * Span * A.Slope',
    '            + (-2.f * T3 + 3.f * T2) * B.Source',
    '            + (T3 - T2) * Span * B.Slope) / 60.f;',
    '    }', '    return PaceTime - ExtraDuration;', '}', '}', '']
(P / 'Source/FPSGAME/Weapons/Super90LoaderPushTiming.h').write_text('\n'.join(header), encoding='utf-8')
audio = json.loads((O.parent / 'Super90LoaderR16_20261009/audio_provenance.json').read_text())
report = dict(revision='Super90LoaderR25-20261012', source=str(source),
    stroke_axis_metres=axis.tolist(), stroke_length_metres=float(np.linalg.norm(axis)),
    source_frame_at_30_percent=split_source,
    knots=[dict(pace=x, source=y, slope=float(m)) for x, y, m in zip(pace, frames, slopes)],
    fps=60, base_rate=1.3, old_push_seconds=24/60/1.3, new_push_seconds=30/60/1.3,
    alignment_seconds=18/60/1.3, drive_seconds=12/60/1.3,
    cues=[dict(asset=c['asset'], source_frame=c['animation_frame'],
               pace_frame=runtime_frame(c['animation_frame'])) for c in audio['audio']],
    runtime_tested=False)
(O / 'timing.json').write_text(json.dumps(report, indent=2), encoding='utf-8')
print('R25_AUTHORED', json.dumps({k: report[k] for k in ('source_frame_at_30_percent', 'old_push_seconds', 'alignment_seconds', 'drive_seconds')}))
