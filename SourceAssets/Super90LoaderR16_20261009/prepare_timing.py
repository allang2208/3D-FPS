"""Compress the existing R15 full drive; preserve pose, contact and camera together."""
from pathlib import Path
import json
import numpy as np
from scipy.interpolate import PchipInterpolator
from scipy.optimize import brentq
O=Path(__file__).parent;P=O.parents[1];R15=O.parent/'Super90LoaderR15_20261009'
old=json.loads((R15/'timing.json').read_text())
# Output R16 -> R15 source. Drive 86..122 becomes 86..110 (36 -> 24 frames).
# Tighten only the initial hand release by two frames; keep its complete path.
knots=[[0,0],[74,74],[86,86],[90,94],[95,101],[101,109],
       [106,116],[110,122],[113,127],[125,139],[144,158],[180,194]]
curve=PchipInterpolator(*np.array(knots).T)
def output(source):return float(brentq(lambda f:float(curve(f))-source,0,180))
timing=dict(revision='LoaderR16-20261009',fps=60,knots=knots,
    source_frames=[float(curve(f)) for f in range(181)],
    contacts_frames=[output(f) for f in old['contacts_frames']],
    dock_frame=output(old['dock_frame']),show_frame=74,hide_frame=125,
    normal_frames=144,empty_frames=180,release_frame=160,cycle_frames=66,
    cycle_release_frame=old['cycle_release_frame'],full_stroke_all_counts=True)
(O/'timing.json').write_text(json.dumps(timing,indent=2),encoding='utf-8')
cameras={}
for name,rows in json.loads((R15/'camera_curves.json').read_text())['curves'].items():
    end=66 if name=='cycle' else timing[name+'_frames']
    sample=PchipInterpolator(np.arange(len(rows)),np.array(rows),axis=0)
    cameras[name]=[list(map(float,sample(f if name=='cycle' else curve(f)))) for f in range(end+1)]
(O/'camera_curves.json').write_text(json.dumps(dict(method='Existing reference camera retimed with R16 full drive',curves=cameras),indent=2))
header=['#pragma once','#include "CoreMinimal.h"','',
    '// Generated by Super90LoaderR16_20261009/prepare_timing.py.',
    '// Original measured camera on the same clock as the complete R16 push.',
    '// X/Y: image displacement / frame width; Z: image roll in degrees.',
    'namespace Super90LoaderCameraReference','{']
for name,rows in cameras.items():
    header.append(f'inline const FVector3f {name.capitalize()}[] = {{')
    header.extend('    {'+', '.join(f'{v:.9f}f' for v in row)+'},' for row in rows)
    header.append('};')
header.append('}')
(P/'Source/FPSGAME/Weapons/Super90LoaderCameraReference.h').write_text('\n'.join(header)+'\n',encoding='utf-8')
# Reuse the seven saved reference cuts without modifying their sound or gain.
audio=json.loads((R15/'audio_provenance.json').read_text())
audio['revision']=timing['revision'];audio['retimed_from']=str(R15/'audio_provenance.json')
for cue in audio['audio']:cue['animation_frame']=output(cue['animation_frame'])
(O/'audio_provenance.json').write_text(json.dumps(audio,indent=2),encoding='utf-8')
header=['#pragma once','#include "CoreMinimal.h"','',
    '// Generated by Super90LoaderR16_20261009/prepare_timing.py.',
    '// The R15 reference cuts are unchanged; only the drive clock is tighter.',
    'namespace Super90LoaderAudioReference','{',
    'struct FCue { const TCHAR* Asset; float Frame; float CycleFrame; };',
    'inline constexpr FCue Cues[] = {']
for cue in audio['audio']:
    name=cue['asset'].rsplit('/',1)[1];cycle=cue['cycle_frame'] if cue['cycle_frame'] is not None else -1
    header.append('    {TEXT("'+cue['asset']+'.'+name+'"), '+f'{cue["animation_frame"]:.6f}f, {cycle:.6f}f'+'},')
header+=['};','}']
(P/'Source/FPSGAME/Weapons/Super90LoaderAudioReference.h').write_text('\n'.join(header)+'\n',encoding='utf-8')
print(json.dumps({k:v for k,v in timing.items() if k not in ('source_frames','knots')},indent=2))
