"""Dual kukri rift ribbons (空间扰动 / 剑气) -> Source/FPSGAME/Weapons/Kukri/KukriDualRiftRibbons.h.

Same ribbons as the single kukri's swings (SourceAssets/Kukri20261020/author_kukri_rift.py, M_RuneRift: U along time --
the material reveals it with SweepProgress --, V across, the edges feathered), written in the viewmodel's mesh component
space (cm), the frame of every baked dual clip.
  Dual heavy release (the crossing X, author_dual_heavy.py).  R15 (user: "make the space distortion standard straight
  lines forming an X"): two straight bands at DEPTH cm in front of the eye, one per blade -- the right's from the upper
  right through the crosshair to the lower left, the left's mirrored -- crossing on the crosshair; each band faces the
  camera (its width runs across the view ray) and tapers a little toward its ends.  R13/R14 baked the blades' own arcs
  (two crescents near the lens).
Run:  python -I author_dual_rift.py
"""
import math
import sys
from pathlib import Path

import numpy as np

P = Path(__file__).resolve().parent
sys.path.insert(0, str(P))
sys.path.insert(0, str(P.parent / 'Kukri20261020'))
from kmath import cam_to_mesh  # noqa: E402

OUT = P.parents[1] / 'Source' / 'FPSGAME' / 'Weapons' / 'Kukri' / 'KukriDualRiftRibbons.h'
STATIONS = 40
DEPTH = 55.0                      # cm in front of the eye (the blades cut at 22-45 cm, the target stands at ~1 m+)
ENDS = ((0.62, -0.95), (-0.62, 0.95))   # right band, NDC (x right, y down): upper right -> lower left
HALF_WIDTH = 2.6                  # cm at the middle; 0.45 of it at the ends
WINDOW = (0.045, 0.125)           # KukriRhythm::DualHeavyRift: revealed as the blades cross the frame
TAN_V = math.tan(math.radians(75.0) / 2)
TAN_H = TAN_V * 16 / 9


def cam(ndc):
    return np.array([DEPTH, ndc[0] * DEPTH * TAN_H, -ndc[1] * DEPTH * TAN_V])


def band(a, b):
    a, b = cam(a), cam(b)
    rows = []
    for i in range(STATIONS):
        u = i / (STATIONS - 1)
        c = a + (b - a) * u
        n = np.cross(b - a, c)
        n /= np.linalg.norm(n)
        w = HALF_WIDTH * (0.45 + 0.55 * math.sin(math.pi * u))
        rows.append([cam_to_mesh(c - n * w), cam_to_mesh(c + n * w)])
    return rows


def fmt(rows):
    return ',\n        '.join('{%s}' % ','.join('{%.2ff,%.2ff,%.2ff}' % tuple(float(v) for v in p) for p in row) for row in rows)


def main():
    (ra, rb) = ENDS
    right = band(ra, rb)
    left = band((-ra[0], ra[1]), (-rb[0], rb[1]))
    text = f"""#pragma once

// GENERATED by SourceAssets/DualKukriIdle20261025/author_dual_rift.py -- do not edit by hand.
// Dual kukri rift ribbons in the viewmodel's mesh component space (cm): [station][inner, outer][xyz], as KukriRiftRibbons.
// Dual heavy release (crossing X): two straight bands {DEPTH:.0f} cm ahead, NDC {ENDS[0]} -> {ENDS[1]} and its mirror,
// revealed over {WINDOW} author s.
namespace KukriDualRiftRibbons
{{
    inline constexpr int32 Stations={STATIONS};
    inline constexpr float HeavyRight[Stations][2][3]={{
        {fmt(right)}}};
    inline constexpr float HeavyLeft[Stations][2][3]={{
        {fmt(left)}}};
}}
"""
    OUT.write_text(text, encoding='utf-8')
    span = np.linalg.norm(cam(rb) - cam(ra))
    print('two straight bands, %.0f cm long at %.0f cm, half width %.1f cm; wrote %s' % (span, DEPTH, HALF_WIDTH, OUT))


if __name__ == '__main__':
    main()
