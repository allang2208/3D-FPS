"""Cut the reference mix into discrete loader contacts; preserve pitch/transients."""
from pathlib import Path
import hashlib,json,wave
import numpy as np
from scipy.interpolate import PchipInterpolator
from scipy.optimize import brentq
O=Path(__file__).parent;P=O.parents[1];R14=O.parent/'Super90LoaderR14_20261009'
meta=json.loads((O/'reference_audio_source.json').read_text())
samples=np.load(O/'reference_audio.npy');rate=48000
new=json.loads((O/'timing.json').read_text());old=json.loads((R14/'timing.json').read_text())
new_curve=PchipInterpolator(*np.array(new['knots']).T)
old_curve=PchipInterpolator(*np.array(old['knots']).T)
ref_curve=PchipInterpolator(*np.array(json.loads((R14/'camera_curves.json').read_text())['reference_knots']).T)
def r12(video_frame):return brentq(lambda f:float(ref_curve(f))-video_frame,0,182)
def frame(video_frame):
    base=r12(video_frame)
    previous=brentq(lambda f:float(old_curve(f))-base,0,206)
    return brentq(lambda f:float(new_curve(f))-previous,0,194)
# First shot/reverb ends before the handling region. No shot tail is included.
# The longer ratchet follows the drive transient in the original mixed track.
cuts=[('Draw',218,235),('Dock',246,251),('Drive',252.6,257.5),
      ('Seat',258,269.5),('Detach',269.5,280),
      ('BoltPull',301.4,305.4),('BoltRelease',306.3,313)]
segments=[samples[round(a/60*rate):round(b/60*rate)].copy() for _,a,b in cuts]
# One shared gain keeps the reference relative strengths. No invented layers/EQ.
peak=max(float(np.max(np.abs(x))) for x in segments)
gain=10**(-3/20)/peak
dest=O/'Wav';dest.mkdir(exist_ok=True)
recipe=dict(revision='LoaderR15-20261009',source=meta['source'],source_sha256=meta['sha256'],
    source_kind='User-supplied Delta Force gameplay recording; original mixed audio, not isolated stems',
    license_note='Local derivative requested by user. No redistribution license inferred from the recording.',
    processing='Frame cuts, shared gain to -3 dBFS peak, 1 ms fade-in and 6 ms fade-out; original speed/pitch and stereo. No replacement foley.',
    sample_rate=rate,channels=2,gain=gain,auditioned=False,game_tested=False,audio=[])
for (role,start,end),data in zip(cuts,segments):
    data*=gain
    n=round(.001*rate);data[:n]*=np.linspace(0,1,n)[:,None]
    n=round(.006*rate);data[-n:]*=np.linspace(1,0,n)[:,None]
    path=dest/('S_Super90_Loader_'+role+'.wav')
    with wave.open(str(path),'wb') as w:
        w.setnchannels(2);w.setsampwidth(2);w.setframerate(rate)
        w.writeframes(np.rint(data*32767).astype('<i2').tobytes())
    recipe['audio'].append(dict(role=role,output=str(path),reference_frames=[start,end],
        reference_seconds=[start/60,end/60],duration_seconds=len(data)/rate,
        animation_frame=frame(start),cycle_frame=(r12(start)-130)*66/52 if role.startswith('Bolt') else None,
        asset='/Game/Weapons/Super90/Speedloader20261007/ReferenceAudio20261009/'+path.stem,
        output_sha256=hashlib.sha256(path.read_bytes()).hexdigest()))
(O/'audio_provenance.json').write_text(json.dumps(recipe,indent=2),encoding='utf-8')
header=['#pragma once','#include "CoreMinimal.h"','',
    '// Generated by Super90LoaderR15_20261009/prepare_audio.py from the user reference.',
    '// Per-contact cuts at original speed; trigger on the same clock as the R15 pose.',
    'namespace Super90LoaderAudioReference','{',
    'struct FCue { const TCHAR* Asset; float Frame; float CycleFrame; };',
    'inline constexpr FCue Cues[] = {']
for row in recipe['audio']:
    name=row['asset'].rsplit('/',1)[1]
    cycle=row['cycle_frame'] if row['cycle_frame'] is not None else -1
    header.append('    {TEXT("'+row['asset']+'.'+name+'"), '+f'{row["animation_frame"]:.6f}f, {cycle:.6f}f'+'},')
header+=['};','}']
(P/'Source/FPSGAME/Weapons/Super90LoaderAudioReference.h').write_text('\n'.join(header)+'\n',encoding='utf-8')
print(json.dumps(dict(gain=gain,cues=[{k:r[k] for k in ['role','animation_frame','cycle_frame','duration_seconds']} for r in recipe['audio']]),indent=2))
