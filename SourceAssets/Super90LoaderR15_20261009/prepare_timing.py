"""Retime the accepted R14 poses, contacts, grip deltas and measured camera together."""
from pathlib import Path
import json
import numpy as np
from scipy.interpolate import PchipInterpolator
from scipy.optimize import brentq

O=Path(__file__).parent;P=O.parents[1];R14=O.parent/'Super90LoaderR14_20261009'
old=json.loads((R14/'timing.json').read_text())
# R15 output frame -> accepted R14 frame. Complete push: 48 -> 36 frames.
# Accelerate through the middle, brake at full travel, retain release/regrip.
knots=[[0,0],[74,74],[86,86],[94,96],[101,104],[109,116],
       [116,126],[122,134],[127,139],[139,151],[158,170],[194,206]]
curve=PchipInterpolator(*np.array(knots).T)
def output(source):return float(brentq(lambda f:float(curve(f))-source,0,194))
timing=dict(revision='LoaderR15-20261009',fps=60,knots=knots,
    source_frames=[float(curve(f)) for f in range(195)],
    contacts_frames=[output(f) for f in old['contacts_frames']],
    dock_frame=output(old['dock_frame']),show_frame=74,hide_frame=139,
    normal_frames=158,empty_frames=194,release_frame=174,cycle_frames=66,
    cycle_release_frame=old['cycle_release_frame'],full_stroke_all_counts=True)
(O/'timing.json').write_text(json.dumps(timing,indent=2),encoding='utf-8')
cameras={}
for name,rows in json.loads((R14/'camera_curves.json').read_text())['curves'].items():
    end=66 if name=='cycle' else timing[name+'_frames']
    sample=PchipInterpolator(np.arange(len(rows)),np.array(rows),axis=0)
    cameras[name]=[list(map(float,sample(f if name=='cycle' else curve(f)))) for f in range(end+1)]
(O/'camera_curves.json').write_text(json.dumps(dict(method='Accepted R14 reference motion on R15 pose clock',curves=cameras),indent=2))
header=['#pragma once','#include "CoreMinimal.h"','',
    '// Generated by Super90LoaderR15_20261009/prepare_timing.py.',
    '// Accepted R14 measured camera, retimed with the preserved pose and contact clock.',
    '// X/Y: image displacement / frame width; Z: image roll in degrees.',
    'namespace Super90LoaderCameraReference','{']
for name,rows in cameras.items():
    header.append(f'inline const FVector3f {name.capitalize()}[] = {{')
    header.extend('    {'+', '.join(f'{v:.9f}f' for v in row)+'},' for row in rows)
    header.append('};')
header.append('}')
(P/'Source/FPSGAME/Weapons/Super90LoaderCameraReference.h').write_text('\n'.join(header)+'\n',encoding='utf-8')
print(json.dumps({k:v for k,v in timing.items() if k!='source_frames'},indent=2))
