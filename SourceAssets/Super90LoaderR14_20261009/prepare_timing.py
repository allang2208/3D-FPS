"""Retime the preserved R12 path and derive camera samples from the user video."""
from pathlib import Path
import json, math
import numpy as np
from scipy.interpolate import PchipInterpolator
from scipy.optimize import brentq
O=Path(__file__).parent
# Output frame -> untouched R12 source frame. Push 86..114 occupies 86..134;
# the complete release/rack/regrip follows it. No shoulder or wrist key is edited.
knots=[[0,0],[74,74],[86,86],[96,90],[104,96],[116,104],[126,110],
       [134,114],[139,116],[151,127],[170,146],[206,182]]
curve=PchipInterpolator(*np.array(knots).T)
def output(source):return float(brentq(lambda f:float(curve(f))-source,0,206))
source_frames=[float(curve(f)) for f in range(207)]
contacts=[output(90+4*i) for i in range(7)]
timing=dict(revision='LoaderR14-20261009',fps=60,knots=knots,source_frames=source_frames,
    contacts_frames=contacts,dock_frame=output(87),show_frame=74,hide_frame=151,
    normal_frames=170,empty_frames=206,release_frame=186,cycle_frames=66,
    cycle_release_frame=66*32/52,full_stroke_all_counts=True)
(O/'timing.json').write_text(json.dumps(timing,indent=2),encoding='utf-8')
# Corresponding phases observed in the capture: push ends as the palm opens
# at 258, not at 254 (the hand is still driving the post at 254).
ref_knots=[[0,164],[26,190],[74,232],[87,246],[114,258],[125,269],
           [143,285],[147,293],[156,302],[162,308],[182,325]]
reference_curve=PchipInterpolator(*np.array(ref_knots).T)
ref=json.loads((O/'reference_camera.json').read_text())
samples=np.array([[r['x_width'],r['y_width'],r['roll_degrees']] for r in ref['samples']])
sample_curve=PchipInterpolator(np.arange(164,326),samples,axis=0)
def measured(frame):return sample_curve(float(reference_curve(frame)))
def smooth(t):t=max(0,min(1,t));return t*t*t*(t*(t*6-15)+10)
def keys(empty=False,cycle=False):
    end=66 if cycle else 206 if empty else 170
    rows=[]
    for f in range(end+1):
        if cycle:
            src=130+f*52/66
            value=measured(src)-measured(130)
            value*=smooth(f/12)
        else:
            src=source_frames[f]
            value=measured(src)
        # The video changes its resting aim between entry and exit. Preserve
        # all measured motion through the force phases, then resolve only the
        # final handoff to zero so a reload never leaves a persistent aim offset.
        if cycle:weight=1-smooth((f-(end-12))/12)
        elif empty:weight=1-smooth((src-170)/12)
        else:weight=1-smooth((src-126)/20)
        rows.append([float(x*weight) for x in value])
    rows[0]=[0.,0.,0.];rows[-1]=[0.,0.,0.]
    return rows
cameras={k:keys(**v) for k,v in {'normal':{},'empty':{'empty':True},'cycle':{'empty':True,'cycle':True}}.items()}
(O/'camera_curves.json').write_text(json.dumps(dict(reference_knots=ref_knots,
    method='Frame-matched measured screen translation/roll; only terminal handoff anchored to zero; no synthetic impact pulses',
    normal_inferred=True,scale_not_applied='Affine scale includes perspective/parallax; no measured FOV or 3D translation exists',curves=cameras),indent=2),encoding='utf-8')
header=['#pragma once','#include "CoreMinimal.h"','',
    '// Generated by Super90LoaderR14_20261009/prepare_timing.py from the user recording.',
    '// X/Y are image displacement divided by frame width; Z is image roll in degrees.',
    '// Sampled on the same retimed 60 Hz clock as the preserved R12 pose path.',
    'namespace Super90LoaderCameraReference','{']
for name,rows in cameras.items():
    header.append(f'inline const FVector3f {name.capitalize()}[] = {{')
    header.extend('    {'+', '.join(f'{v:.9f}f' for v in row)+'},' for row in rows)
    header.append('};')
header.append('}')
(O.parents[1]/'Source/FPSGAME/Weapons/Super90LoaderCameraReference.h').write_text('\n'.join(header)+'\n',encoding='utf-8')
print(json.dumps({k:v for k,v in timing.items() if k!='source_frames'},indent=2))
