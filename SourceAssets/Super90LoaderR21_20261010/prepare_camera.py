"""Keep measured background movement; add the slower body response on its clock."""
import json,math,shutil,hashlib
from pathlib import Path
from motion import camera_response
O=Path(__file__).parent;P=O.parents[1]
reference=json.loads((O.parent/'Super90LoaderR16_20261009/camera_curves.json').read_text())['curves']
tan_half=math.tan(math.radians(56));curves={}
for branch,rows in reference.items():
    result=[]
    for f,(x,y,roll) in enumerate(rows):
        pitch_add,yaw_add,roll_add=camera_response(branch,f)
        pitch=math.atan(2*y*tan_half)+math.radians(pitch_add)
        yaw=-math.atan(2*x*tan_half)+math.radians(yaw_add)
        result.append([-math.tan(yaw)/(2*tan_half),math.tan(pitch)/(2*tan_half),roll-roll_add])
    curves[branch]=result
(O/'camera_curves.json').write_text(json.dumps(dict(method='R16 measured camera with delayed R21 load response; original source clock retained',curves=curves),indent=2),encoding='utf-8')
file=P/'Source/FPSGAME/Weapons/Super90LoaderCameraReference.h'
backup=O/'Before/Source/FPSGAME/Weapons/Super90LoaderCameraReference.h';backup.parent.mkdir(parents=True,exist_ok=True)
if not backup.exists():shutil.copy2(file,backup)
header=['#pragma once','#include "CoreMinimal.h"','',
    '// Generated by Super90LoaderR21_20261010/prepare_camera.py.',
    '// R16 measured background track plus delayed, smaller R21 load response.',
    '// Source timing is unchanged; X/Y are image displacement / frame width, Z is image roll.',
    'namespace Super90LoaderCameraReference','{']
for name,rows in curves.items():
    header.append(f'inline const FVector3f {name.capitalize()}[] = {{')
    header.extend('    {'+', '.join(f'{v:.9f}f' for v in row)+'},' for row in rows);header.append('};')
header.append('}');file.write_text('\n'.join(header)+'\n',encoding='utf-8')
(O/'camera_source.json').write_text(json.dumps(dict(file=str(file),sha256=hashlib.sha256(file.read_bytes()).hexdigest(),reference='R16',phase_lag_source_frames=[1.4,3.0],runtime_tested=False),indent=2),encoding='utf-8')
print('R21_CAMERA_SOURCE_SAVED',flush=True)
