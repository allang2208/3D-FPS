"""R26 push clock: keep R25's split, remove its mid-alignment stall.

R25 used one Hermite span 86->104 with unit entry slope; to average 0.36x it
dipped to ~0.12x at pace 96. R26 lets the dock absorb the entry speed, holds an
even slow alignment and then accelerates once into the seat. Knots are dense
(one per pace frame) so the runtime Hermite reproduces the designed velocity.
"""
import numpy as np
from scipy.interpolate import PchipInterpolator
from scipy.optimize import brentq

SPLIT = 92.502451001          # R25: 30 % of the gun-space push (R21 source poses)
BEGIN, ALIGN, SEAT = 86., 104., 116.
SOURCE_SEAT = 110.
EXTRA = SEAT - SOURCE_SEAT    # six pace frames, unchanged from R25
# Designed slope d(source)/d(pace). Entry 1.0 keeps C1 with the 1x approach;
# the tube docks at source 87.01, after which the alignment holds ~0.3x.
CONTROL = [(86, 1.00), (87, .80), (88, .52), (89, .38), (90, .32), (92, .29), (95, .28), (98, .29),
           (100, .33), (102, .43), (104, .62), (106, 1.05), (108, 1.45), (110, 1.72), (112, 1.80),
           (114, 1.62), (115, 1.35), (116, 1.00)]


def _velocity(scale_a, scale_b):
    pts = [(p, v * (scale_a if BEGIN < p < ALIGN else scale_b if ALIGN < p < SEAT else 1.)) for p, v in CONTROL]
    return PchipInterpolator(*np.array(pts, float).T)


def _area(v, a, b):
    x = np.linspace(a, b, 4001)
    return float(np.trapezoid(v(x), x))


scale_a = brentq(lambda s: _area(_velocity(s, 1.), BEGIN, ALIGN) - (SPLIT - BEGIN), .3, 3.)
scale_b = brentq(lambda s: _area(_velocity(scale_a, s), ALIGN, SEAT) - (SOURCE_SEAT - SPLIT), .3, 3.)
VELOCITY = _velocity(scale_a, scale_b)
_fine = np.linspace(BEGIN, SEAT, 30001)
_integral = BEGIN + np.r_[0., np.cumsum((VELOCITY(_fine[1:]) + VELOCITY(_fine[:-1])) * .5 * np.diff(_fine))]
PACE = np.arange(BEGIN, SEAT + 1.)
KNOTS = [(float(p), float(np.interp(p, _fine, _integral)), float(VELOCITY(p))) for p in PACE]
KNOTS[0] = (BEGIN, BEGIN, 1.)
KNOTS[int(ALIGN - BEGIN)] = (ALIGN, SPLIT, KNOTS[int(ALIGN - BEGIN)][2])
KNOTS[-1] = (SEAT, SOURCE_SEAT, 1.)


def source_frame(pace):
    """Exactly the runtime Hermite in Super90LoaderPushTiming.h, in frames."""
    if pace <= BEGIN:
        return pace
    if pace >= SEAT:
        return pace - EXTRA
    for (pa, sa, ma), (pb, sb, mb) in zip(KNOTS, KNOTS[1:]):
        if pace > pb:
            continue
        span = pb - pa
        t = (pace - pa) / span
        t2, t3 = t * t, t * t * t
        return ((2 * t3 - 3 * t2 + 1) * sa + (t3 - 2 * t2 + t) * span * ma
                + (-2 * t3 + 3 * t2) * sb + (t3 - t2) * span * mb)
    return pace - EXTRA


def slope(pace, h=1e-3):
    return (source_frame(pace + h) - source_frame(pace - h)) / (2 * h)


def pace_frame(source):
    """Inverse clock for authoring layers in perceived (pace) time."""
    if source <= BEGIN:
        return source
    if source >= SOURCE_SEAT:
        return source + EXTRA
    return float(brentq(lambda p: source_frame(p) - source, BEGIN, SEAT, xtol=1e-9))


def header():
    lines = ['#pragma once', '#include "CoreMinimal.h"', '',
             '// Generated by Super90LoaderR26_20261016/author_timing.py.',
             '// R26 keeps the R25 split (30% of the stroke at pace 104, seated at 116)',
             '// but removes its mid-alignment stall: the dock absorbs the entry speed,',
             '// alignment holds an even slow pace, then one acceleration into the seat.',
             '// This clock is shared by poses, grip profiles, props, audio and camera.',
             'namespace Super90LoaderPushTiming', '{',
             'inline constexpr float ExtraDuration = 6.f / 60.f;',
             'inline float SourceTime(float PaceTime)', '{',
             '    const float Frame = PaceTime * 60.f;',
             '    if (Frame <= 86.f) return PaceTime;',
             '    if (Frame >= 116.f) return PaceTime - ExtraDuration;',
             '    struct FKnot { float Pace; float Source; float Slope; };',
             '    static constexpr FKnot Knots[] = {']
    lines += [f'        {{{p:.9f}f, {s:.9f}f, {m:.9f}f}},' for p, s, m in KNOTS]
    lines += ['    };',
              '    for (int32 I = 1; I < UE_ARRAY_COUNT(Knots); ++I)', '    {',
              '        const FKnot& A = Knots[I - 1];', '        const FKnot& B = Knots[I];',
              '        if (Frame > B.Pace) continue;',
              '        const float Span = B.Pace - A.Pace;',
              '        const float T = (Frame - A.Pace) / Span;',
              '        const float T2 = T * T, T3 = T2 * T;',
              '        return ((2.f * T3 - 3.f * T2 + 1.f) * A.Source',
              '            + (T3 - 2.f * T2 + T) * Span * A.Slope',
              '            + (-2.f * T3 + 3.f * T2) * B.Source',
              '            + (T3 - T2) * Span * B.Slope) / 60.f;',
              '    }', '    return PaceTime - ExtraDuration;', '}', '}', '']
    return '\n'.join(lines)
