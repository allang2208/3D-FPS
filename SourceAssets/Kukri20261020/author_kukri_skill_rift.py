"""Kukri skill rift ribbons (空间扰动 / 剑气 for the sprint attack, 2026-10-24) -> KukriSkillRiftRibbons.h.

Same bake as author_kukri_rift.py (the combo's crescents, which this file leaves alone): the blade's authored path through
the strike, between INNER and OUTER along the grip->tip vector, U along time (M_RuneRift SweepProgress), V across, in the
viewmodel's mesh component space (cm).

  SprintAttack (dashAttack, the two-handed jump chop): one crescent from above the frame down through the crosshair to
  the bottom, over the chop 0.345-0.410 author s (Work/whirl/probe_dash_rift.py: before 0.345 the blade is still over or
  behind the head, after 0.410 it rests below the centre).  The rune sword's sprint overhead has the same crescent
  (SM_RuneRift_Overhead, strength .16).

The whirlwind ring is built at runtime (KukriSkillRift.cpp) from the held blade, not baked here.
Run:  python author_kukri_skill_rift.py
"""
from pathlib import Path

import numpy as np

from author_kukri_rift import crescent, fmt, STATIONS
from author_kukri_sprint import SprintClip
from kmath import mesh_to_cam

P = Path(__file__).resolve().parent
OUT = P.parents[1] / 'Source' / 'FPSGAME' / 'Weapons' / 'Kukri' / 'KukriSkillRiftRibbons.h'
DASH_WINDOW = (0.345, 0.410)        # KukriDashRhythm::RiftStart / RiftEnd


def main():
    clip = SprintClip()
    t0, t1 = DASH_WINDOW
    Ks = [clip.sample(t0 + (t1 - t0) * i / (STATIONS - 1))[1] for i in range(STATIONS)]
    dash = crescent(Ks)
    depth = [float(mesh_to_cam(p)[0]) for row in dash for p in row]
    span = np.linalg.norm(np.asarray(dash[-1][1]) - np.asarray(dash[0][1]))
    print('dash    depth %.1f-%.1f cm, outer edge travels %.1f cm' % (min(depth), max(depth), span))
    text = f"""#pragma once

// GENERATED by SourceAssets/Kukri20261020/author_kukri_skill_rift.py -- do not edit by hand.
// Kukri skill rift ribbons in the viewmodel's mesh component space (cm): [station][inner, outer][xyz].
// U = station / (Stations - 1) is the reveal along the strike (M_RuneRift SweepProgress); V = 0 / 1 across.
// Sprint attack window (author s): {DASH_WINDOW}.
namespace KukriSkillRiftRibbons
{{
    inline constexpr int32 Stations={STATIONS};
    inline constexpr float Dash[Stations][2][3]={{
        {fmt(dash)}}};
}}
"""
    OUT.write_text(text, encoding='utf-8')
    print('wrote', OUT)


if __name__ == '__main__':
    main()
