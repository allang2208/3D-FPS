"""Generate Source/FPSGAME/Weapons/Kukri/KukriLeftRest.h: the left arm's natural hanging pose.

The viewmodel's left arm hangs naturally in the single-hand Idle clip (kukri_rig's IDLE_L target, below the frame).  The
whirlwind clip raises it as a guard fist, which pushes a dual-wield off-hand weapon into the sightline; blending the left
chain to these idle locals instead puts the arm back down.  Locals are parent-space (same convention as the clips).

Run:  python author_kukri_left_rest.py
"""
import json
from pathlib import Path

P = Path(__file__).resolve().parent
OUT = P.parents[1] / 'Source' / 'FPSGAME' / 'Weapons' / 'Kukri' / 'KukriLeftRest.h'

data = json.loads((P / 'Clips' / 'Idle.json').read_text('utf-8'))
frame = data['frames'][0]
names = data['bones']
order = [n for n in names if n == 'clavicle_l' or n.startswith(('upperarm_l', 'upperarm_twist_0', 'lowerarm_l',
         'lowerarm_twist_0', 'hand_l', 'index_', 'middle_', 'ring_', 'pinky_', 'thumb_'))]
order = [n for n in order if n.endswith('_l')]
rows = []
for n in order:
    p, q, s = frame[n][0], frame[n][1], frame[n][2]
    rows.append('        {TEXT("%s"),{%.5ff,%.5ff,%.5ff},{%.6ff,%.6ff,%.6ff,%.6ff}},' % (
        n, p[0], p[1], p[2], q[1], q[2], q[3], q[0]))
text = f'''#pragma once

#include "CoreMinimal.h"

// GENERATED by SourceAssets/Kukri20261020/author_kukri_left_rest.py -- do not edit by hand.
/**
 * 左臂自然垂放姿势（单持 Idle 第 0 帧的局部旋转），用于双持旋风时把副手手臂放下、离开视野。
 * 骨骼按 parent space 的局部变换给出（与 clip 数据同一约定），位置取 Idle 的原始数值。
 */
namespace KukriLeftRest
{{
    struct FBone
    {{
        const TCHAR* Name;
        float P[3];
        float Q[4];     // x, y, z, w
    }};
    inline constexpr FBone Bones[]={{
{chr(10).join(rows)}
    }};
    inline constexpr int32 Count=UE_ARRAY_COUNT(Bones);
}}
'''
OUT.write_bytes(text.encode('utf-8'))
print('wrote', OUT, len(rows), 'bones')
