"""Write Source/FPSGAME/Weapons/Kukri/OffhandKukriAuthoredStrike.h from the authored flourish data.

Inputs: Work/strike/strike_keys.json (single-thrust pose keys from author_strike.py) and
Saved/Reference/DualPistolKukriBV1hQnh6hEio20261025/thrust_curve.json (21-sample camera + blur, 30 Hz,
from Reference/curve_thrust.py). Camera space is X forward, Y right, Z up, cm; quaternions are UE
FQuat (x, y, z, w). Wrist offsets are relative to the pistol's hand_r bone position.
"""
import json
from pathlib import Path
import numpy as np
from scipy.spatial.transform import Rotation as R

P = Path(__file__).resolve().parent
ROOT = P.parents[1]
DEST = ROOT / 'Source/FPSGAME/Weapons/Kukri/OffhandKukriAuthoredStrike.h'
CURVE = ROOT / 'Saved/Reference/DualPistolKukriBV1hQnh6hEio20261025/thrust_curve.json'

keys = json.loads((P / 'Work/strike/strike_keys.json').read_text(encoding='utf-8'))
curve = json.loads(CURVE.read_text(encoding='utf-8'))


def vec(v): return ','.join(f'{x:.6f}' for x in v)


def quat(m):
    q = R.from_matrix(np.asarray(m)[:3, :3]).as_quat()
    return f'FQuat({vec(q / np.linalg.norm(q))})'


lines = ['#pragma once', '#include "CoreMinimal.h"',
         '// Generated by SourceAssets/DualPistolKukri20261025/export_strike.py; do not edit by hand.',
         '// Pistol + offhand kukri quick melee (F): one left-hand thrust, BV1hQnh6hEio file 40.33-41.00 s.',
         '// Camera space: X forward, Y right, Z up, cm. Key wrists are relative to the pistol hand_r.',
         'namespace OffhandKukriStrike',
         '{',
         'struct FKey',
         '{',
         '    float T;',
         '    FVector Wrist;          // left wrist offset from the right hand bone, camera space',
         '    FQuat Hand;             // left hand rotation, camera space',
         '    FVector Shoulder,Pole;  // left arm solver targets, camera space',
         '    float Clavicle;         // share of the upper arm\'s deformation the clavicle follows',
         '    FTransform Framing;     // gun framing; replaces OffhandKukriPose::HipFraming while striking',
         '};',
         'inline const FKey Keys[]={']
for k in keys['keys']:
    framing = np.array(k['framing'])
    lines.append('    {%.3ff,FVector(%s),%s,FVector(%s),FVector(%s),%.3ff,FTransform(%s,FVector(%s))},'
                 % (k['t'], vec(k['wrist_offset']), quat(k['left_hand']), vec(k['left_shoulder']),
                    vec(k['left_pole']), k.get('clavicle', 0.), quat(framing), vec(framing[:3, 3])))
lines += ['};',
          f'inline constexpr int32 KeyCount={len(keys["keys"])};',
          f'inline constexpr float Length={keys["length"]:.3f}f;',
          '// Swing whooshes and blade contacts on the same author clock (the camera kicks land on the contacts).',
          f'inline constexpr int32 SlashCount={len(keys["contacts"])};',
          'inline constexpr float Swings[SlashCount]={%s};' % ','.join('%.3ff' % t for t in keys['swings']),
          'inline constexpr float Contacts[SlashCount]={%s};' % ','.join('%.3ff' % t for t in keys['contacts']),
          '',
          '/** Two-bone IK inputs at author time T: linear positions, slerped rotations. */',
          'inline void SamplePose(float T,FVector& Wrist,FQuat& Hand,FVector& Shoulder,FVector& Pole,FTransform& Framing)',
          '{',
          '    if(T<=Keys[0].T){Wrist=Keys[0].Wrist;Hand=Keys[0].Hand;Shoulder=Keys[0].Shoulder;Pole=Keys[0].Pole;Framing=Keys[0].Framing;return;}',
          '    int32 I=0;',
          '    while(I<KeyCount-2&&T>=Keys[I+1].T)++I;',
          '    const float F=FMath::Clamp((T-Keys[I].T)/FMath::Max(Keys[I+1].T-Keys[I].T,1e-4f),0.f,1.f);',
          '    const FKey& A=Keys[I];const FKey& B=Keys[I+1];',
          '    Wrist=FMath::Lerp(A.Wrist,B.Wrist,F);',
          '    Hand=FQuat::Slerp(A.Hand,B.Hand,F).GetNormalized();',
          '    Shoulder=FMath::Lerp(A.Shoulder,B.Shoulder,F);',
          '    Pole=FMath::Lerp(A.Pole,B.Pole,F);',
          '    Framing=FTransform(FQuat::Slerp(A.Framing.GetRotation(),B.Framing.GetRotation(),F).GetNormalized(),',
          '        FMath::Lerp(A.Framing.GetLocation(),B.Framing.GetLocation(),F));',
          '}',
          '',
          '/** Clavicle share at author time T (0 at both ends: the hip stance keeps its bind clavicle). */',
          'inline float SampleClavicle(float T)',
          '{',
          '    if(T<=Keys[0].T)return Keys[0].Clavicle;',
          '    int32 I=0;',
          '    while(I<KeyCount-2&&T>=Keys[I+1].T)++I;',
          '    const float F=FMath::Clamp((T-Keys[I].T)/FMath::Max(Keys[I+1].T-Keys[I].T,1e-4f),0.f,1.f);',
          '    return FMath::Lerp(Keys[I].Clavicle,Keys[I+1].Clavicle,F);',
          '}',
          '',
          '// Reference camera registration, 30 Hz (Reference/curve_thrust.py): yaw +right, pitch +up,',
          '// roll +clockwise; fov = vertical FOV delta; blur = normalised background-blur envelope.',
          f'inline constexpr int32 CameraSamples={curve["samples"]};']

for name in ('yaw', 'pitch', 'roll', 'fov', 'blur'):
    values = ','.join(f'{v:.2f}f' if name != 'blur' else f'{v:.3f}f' for v in curve[name])
    lines.append(f'inline constexpr float Camera{name.capitalize()}[CameraSamples]={{{values}}};')

lines += ['',
          'inline float SampleCurve(const float (&Curve)[CameraSamples],float Time)',
          '{',
          '    const float X=FMath::Clamp(Time*30.f,0.f,float(CameraSamples-1));',
          '    const int32 I=FMath::Min(int32(X),CameraSamples-2);',
          '    return FMath::Lerp(Curve[I],Curve[I+1],X-I);',
          '}',
          '',
          '/** Strike camera (degrees + vertical FOV delta + blur strength) at author time T. */',
          'inline void Camera(float T,FRotator& Rotation,float& Fov,float& BlurStrength)',
          '{',
          '    Rotation=FRotator(SampleCurve(CameraPitch,T),SampleCurve(CameraYaw,T),SampleCurve(CameraRoll,T));',
          '    Fov=SampleCurve(CameraFov,T);',
          '    BlurStrength=SampleCurve(CameraBlur,T);',
          '}',
          '}']
DEST.write_text('\n'.join(lines) + '\n', encoding='utf-8', newline='\n')
print('WROTE', DEST, len(keys['keys']), 'keys', curve['samples'], 'camera samples')
