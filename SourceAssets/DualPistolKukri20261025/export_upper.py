"""Write Source/FPSGAME/Weapons/Kukri/OffhandKukriAuthoredUppercut.h from the authored uppercut data.

Inputs: Work/upper/offhand_upper_keys.json (77 pose keys, digits, kukri_in_hand from author_upper.py)
and the Upper crescent table in Source/FPSGAME/Weapons/Kukri/KukriRiftRibbons.h, which is in the
viewmodel's mesh component space. The offhand runtime anchors its rift at the camera, so the ribbon
is exported in camera space (X forward, Y right, Z up, cm): a mesh-space point p maps to cam
(-p.y, p.x, p.z), and the left/right mirror negates cam Y, giving (-p.y, -p.x, p.z) per station.
Quaternions are UE FQuat (x, y, z, w). Key wrists are relative to the evaded pistol hand_r.
"""
import json
import re
from pathlib import Path
import numpy as np
from scipy.spatial.transform import Rotation as R

P = Path(__file__).resolve().parent
ROOT = P.parents[1]
DEST = ROOT / 'Source/FPSGAME/Weapons/Kukri/OffhandKukriAuthoredUppercut.h'

data = json.loads((P / 'Work/upper/offhand_upper_keys.json').read_text(encoding='utf-8'))
keys = data['keys']


def vec(v): return ','.join(f'{x:.6f}' for x in v)


def quat(m):
    q = R.from_matrix(np.asarray(m)[:3, :3]).as_quat()
    return f'FQuat({vec(q / np.linalg.norm(q))})'


# KukriRiftRibbons::Upper -> camera space, mirrored: mesh p -> (-p.y, -p.x, p.z).
rift_src = (ROOT / 'Source/FPSGAME/Weapons/Kukri/KukriRiftRibbons.h').read_text(encoding='utf-8')
upper_block = re.search(r'float Upper\[Stations\]\[2\]\[3\]=\{(.*?)\};', rift_src, re.S).group(1)
pts = [float(x) for x in re.findall(r'-?\d+\.\d+', upper_block)]
assert len(pts) == 40 * 2 * 3
rift = [((-pts[i * 6 + 1], -pts[i * 6], pts[i * 6 + 2]),
         (-pts[i * 6 + 4], -pts[i * 6 + 3], pts[i * 6 + 5])) for i in range(40)]

lines = ['#pragma once', '#include "CoreMinimal.h"',
         '// Generated by SourceAssets/DualPistolKukri20261025/export_upper.py; do not edit by hand.',
         '// Pistol + offhand kukri uppercut (swordUppercut): the main-hand Uppercut clip mirrored to',
         '// the left hand; the gun hand evades along the clip\'s balance-hand path. Camera space:',
         '// X forward, Y right, Z up, cm. Key wrists are relative to the pistol hand_r.',
         'namespace OffhandKukriUpper',
         '{',
         'struct FDigit { const TCHAR* Name; FQuat LocalRotation; };',
         '// Forward grip: the clip\'s right-hand fingers mirrored onto the V7 _l bones (bind-derived',
         '// mirror), baked at the contact frame (t=0.35). Applied while T is inside the digits window.',
         'inline const FDigit Digits[]={']
for name, q in sorted(data['digits'].items()):
    lines.append('    {TEXT("%s"),FQuat(%s)},' % (name, vec(q)))
lines += ['};',
          f'inline constexpr int32 DigitCount={len(data["digits"])};',
          f'inline constexpr float DigitsAt={data["digits_window"][0]:.3f}f,DigitsEnd={data["digits_window"][1]:.3f}f;',
          '// Mirrored SM_Kukri (WPN_root) in the left hand, cm: the main-hand forward grip, reflected.',
          'inline const FTransform KukriInHand=FTransform(%s,FVector(%s));'
          % (quat(data['kukri_in_hand']), vec(np.asarray(data['kukri_in_hand'])[:3, 3])),
          '',
          'struct FKey',
          '{',
          '    float T;',
          '    FVector Wrist;          // left wrist offset from the right hand bone, camera space',
          '    FQuat Hand;             // left hand rotation, camera space',
          '    FVector Shoulder,Pole;  // left arm solver targets, camera space',
          '    float Clavicle;         // share of the upper arm\'s deformation the clavicle follows',
          '    FTransform Framing;     // gun framing incl. the right-hand evade; replaces HipFraming',
          '};',
          'inline const FKey Keys[]={']
for k in keys:
    framing = np.array(k['framing'])
    lines.append('    {%.4ff,FVector(%s),%s,FVector(%s),FVector(%s),%.4ff,FTransform(%s,FVector(%s))},'
                 % (k['t'], vec(k['wrist_offset']), quat(k['left_hand']), vec(k['left_shoulder']),
                    vec(k['left_pole']), k['clavicle'], quat(framing), vec(framing[:3, 3])))
lines += ['};',
          f'inline constexpr int32 KeyCount={len(keys)};',
          f'inline constexpr float Length={data["length"]:.4f}f;',
          f'inline constexpr float SwingAt={data["swings"][0]:.3f}f;',
          f'inline constexpr float ContactStart={data["contact"][0]:.3f}f,ContactEnd={data["contact"][1]:.3f}f;',
          '',
          '/** Two-bone IK inputs at author time T: linear positions, slerped rotations. */',
          'inline void SamplePose(float T,FVector& Wrist,FQuat& Hand,FVector& Shoulder,FVector& Pole,FTransform& Framing)',
          '{',
          '    if(T<=Keys[0].T){Wrist=Keys[0].Wrist;Hand=Keys[0].Hand;Shoulder=Keys[0].Shoulder;Pole=Keys[0].Pole;Framing=Keys[0].Framing;return;}',
          '    int32 I=0;',
          '    while(I<KeyCount-2&&T>=Keys[I+1].T)++I;',
          '    const float F=FMath::Clamp((T-Keys[I].T)/FMath::Max(Keys[I+1].T-Keys[I].T,1e-4f),0.f,1.f);',
          '    const FKey& A=Keys[I];const FKey& B=Keys[I+1];',
          '    Wrist=FMath::Lerp(A.Wrist,B.Wrist,F);',
          '    Hand=FQuat::Slerp(A.Hand,B.Hand,F).GetNormalized();',
          '    Shoulder=FMath::Lerp(A.Shoulder,B.Shoulder,F);',
          '    Pole=FMath::Lerp(A.Pole,B.Pole,F);',
          '    Framing=FTransform(FQuat::Slerp(A.Framing.GetRotation(),B.Framing.GetRotation(),F).GetNormalized(),',
          '        FMath::Lerp(A.Framing.GetLocation(),B.Framing.GetLocation(),F));',
          '}',
          '',
          '/** Clavicle share at author time T (0 at both ends: the hip stance keeps its bind clavicle). */',
          'inline float SampleClavicle(float T)',
          '{',
          '    if(T<=Keys[0].T)return Keys[0].Clavicle;',
          '    int32 I=0;',
          '    while(I<KeyCount-2&&T>=Keys[I+1].T)++I;',
          '    const float F=FMath::Clamp((T-Keys[I].T)/FMath::Max(Keys[I+1].T-Keys[I].T,1e-4f),0.f,1.f);',
          '    return FMath::Lerp(Keys[I].Clavicle,Keys[I+1].Clavicle,F);',
          '}',
          '',
          '// Mirrored KukriRiftRibbons::Upper, re-expressed in camera space for a camera-anchored rift:',
          '// mesh p -> cam (-p.y,-p.x,p.z). U = station reveal (SweepProgress), V = 0 / 1 across.',
          'inline constexpr int32 RiftStations=40;',
          'inline constexpr float Rift[RiftStations][2][3]={']
lines += ['    {{%.2ff,%.2ff,%.2ff},{%.2ff,%.2ff,%.2ff}},' % (a[0], a[1], a[2], b[0], b[1], b[2])
          for a, b in rift]
lines[-1] = lines[-1].rstrip(',') + '};'
lines += ['}']
DEST.write_text('\n'.join(lines) + '\n', encoding='utf-8', newline='\n')
print('WROTE', DEST, len(keys), 'keys', len(data['digits']), 'digits', len(rift), 'rift stations')
