"""Write Source/FPSGAME/Weapons/Kukri/OffhandKukriAuthoredPose.h from the accepted author data.

Inputs: grip.json (contact-fitted digits, kukri in hand), candidate.json (hip), candidate_ads.json (ADS),
pose_controls.json. Camera space is X forward, Y right, Z up, cm; quaternions are UE FQuat (x, y, z, w).
- Digits: local rotations of every left-hand descendant (SK_M4_BareArmsV7 bind translations kept).
- Stances: left wrist relative to the pistol's hand_r position, left hand rotation, both shoulders and poles.
- HipFraming: camera-space transform taking the native pistol hip base (location PistolHipViewmodelLocation
  (-2, 3, -6.5), yaw -90) to the authored canted composition; applied as mesh' = HipFraming * mesh.
"""
import json
from pathlib import Path
import numpy as np
from scipy.spatial.transform import Rotation as R

P = Path(__file__).resolve().parent
ROOT = P.parents[1]
DEST = ROOT / 'Source/FPSGAME/Weapons/Kukri/OffhandKukriAuthoredPose.h'
PISTOL_HIP = np.array([-2.0, 3.0, -6.5])


def read(name): return json.loads((P / name).read_text(encoding='utf-8'))
def vec(v): return ','.join(f'{x:.6f}' for x in v)
def quat(m):
    q = R.from_matrix(np.asarray(m)[:3, :3]).as_quat()
    return f'FQuat({vec(q / np.linalg.norm(q))})'


grip = read('grip.json')
hip, ads = read('candidate.json'), read('candidate_ads.json')
controls = read('pose_controls.json')
snapshot = json.loads((ROOT / 'SourceAssets/BareSkinV9Rollout_20261017/Snapshots/01e184ddd1b7.json').read_text(encoding='utf-8-sig'))
names = {b['index']: n for n, b in snapshot['bones'].items()}
parent = {n: names.get(b['parent']) for n, b in snapshot['bones'].items()}
comp = {n: np.array(m) for n, m in grip['digits'].items()}
comp['hand_l'] = np.array(grip['source_hand_l'])
digits = sorted(grip['digits'], key=lambda n: snapshot['bones'][n]['index'])
local = {n: np.linalg.inv(comp[parent[n]]) @ comp[n] for n in digits}


def stance(c):
    l, r = c['poses']['left'], c['poses']['right']
    lw, rw = np.array(l['hand_l']), np.array(r['hand_r'])
    k = c['controls']
    return {'wrist': lw[:3, 3] - rw[:3, 3], 'hand': lw, 'lshoulder': np.array(l['upperarm_l'])[:3, 3], 'lpole': k['left_pole'],
            'rshoulder': np.array(r['upperarm_r'])[:3, 3], 'rpole': k['right_pole']}


G = np.array(hip['gun_composition'])
framing = G.copy(); framing[:3, 3] = G[:3, 3] - G[:3, :3] @ PISTOL_HIP

lines = ['#pragma once', '#include "CoreMinimal.h"',
         '// Generated by SourceAssets/DualPistolKukri20261025/export_runtime.py; do not edit by hand.',
         '// Camera space: X forward, Y right, Z up, cm. Left bones: SK_M4_BareArmsV7. Right: the pistol rig.',
         'namespace OffhandKukriPose', '{', 'inline constexpr int32 Revision=1;',
         'struct FDigit { const TCHAR* Name; FQuat LocalRotation; };',
         '// Accepted M4 VRE vertical-grip fist, contact-fitted to the reversed kukri handle (grip_fit.py).',
         'inline const FDigit Digits[]={']
lines += [f'    {{TEXT("{n}"),{quat(local[n])}}},' for n in digits]
ki = np.array(grip['kukri_in_hand'])
lines += ['};', f'inline constexpr int32 DigitCount={len(digits)};',
          '// Kukri static mesh relative to hand_l (scale removed): reversed, blade out of the pinky side, edge in.',
          f'inline const FTransform KukriInHand=FTransform({quat(ki)},FVector({vec(ki[:3, 3])}));',
          'struct FStance { FVector LeftWristFromRightHand; FQuat LeftHand; FVector LeftShoulder,LeftPole,RightShoulder,RightPole; };']
for label, c in (('Hip', hip), ('Aim', ads)):
    s = stance(c)
    lines.append(f'inline const FStance {label}={{FVector({vec(s["wrist"])}),{quat(s["hand"])},FVector({vec(s["lshoulder"])}),'
                 f'FVector({vec(s["lpole"])}),FVector({vec(s["rshoulder"])}),FVector({vec(s["rpole"])})}};')
lines += ['// mesh\'=HipFraming*mesh in camera space: centred, ~20 degrees counter-clockwise cant (reference hold).',
          f'inline const FTransform HipFraming=FTransform({quat(framing)},FVector({vec(framing[:3, 3])}));',
          '// ADS clock of the pistol + book cross-arm support; the cant unwinds within the first 60 % of ADS-in.',
          'inline constexpr float AimInSeconds=.32f,AimOutSeconds=.28f,BlendSeconds=.24f,ContactReturnSeconds=.18f;',
          'inline constexpr float CantUnwindAim=.6f,TransferDipCm=2.f;',
          'inline float Ease(float X) {return X*X*(3.f-2.f*X);}', '}']
DEST.write_text('\n'.join(lines) + '\n', encoding='utf-8', newline='\n')
print('WROTE', DEST, len(digits), 'digits')
print('hip wrist offset', np.round(stance(hip)['wrist'], 2), 'ads', np.round(stance(ads)['wrist'], 2))
print('framing', np.round(framing, 3))
