"""Retire the used-up iteration outputs of guard V24 after the user accepted r9 (2026-11-22).

py -3.11 archive_work.py
Moves Work/ rounds r1-r8, grid/overlay sheets, author logs, the two regenerable preview blends and the one-off
debug script to D:/FPS3D/FPSGAME/trash/runesword-guard-v24-20261122/. Kept in Work/: r9 sheets and renders (final),
r5_guard.jpg and width_probe.png (cited in keys_guard_v24.json), run_round.sh, probe_sword.*.
The per-file manifest (original path, target, size, SHA-256, reason, replacement) is written to the feature batch on F:
F:/FPSGAMEData/ArtProduction/RuneSword20260913/GuardKuboldV24/Cleanup-20261122/archive-manifest.json
"""
import hashlib
import json
import shutil
from pathlib import Path

HERE = Path(__file__).resolve().parent
WORK = HERE / 'Work'
TRASH = Path('D:/FPS3D/FPSGAME/trash/runesword-guard-v24-20261122')
RECEIPT = Path('F:/FPSGAMEData/ArtProduction/RuneSword20260913/GuardKuboldV24/Cleanup-20261122')
KEEP = {'r9', 'r9_guard.jpg', 'r9_hit.jpg', 'r9_break.jpg', 'r5_guard.jpg', 'width_probe.png', 'run_round.sh',
        'probe_sword.py', 'probe_sword.json'}
REASONS = {
    'preview_Standard.blend': 'regenerated by author_guard_v24.py --no-export',
    'preview_LongGrip.blend': 'regenerated by author_guard_v24.py --long-grip --no-export',
    'sheets': 'reference grid read-out sheets, regenerated by Reference/grid_sheet.py',
    'overlay': 'blade-tracker overlays, regenerated by Reference/measure_blade.py --overlay',
    'debug_eval.py': 'one-off probe for the r2 action-name collision (fixed in the author script)',
}


def sha(p):
    h = hashlib.sha256()
    with open(p, 'rb') as f:
        for chunk in iter(lambda: f.read(1 << 20), b''):
            h.update(chunk)
    return h.hexdigest()


assert WORK.is_dir() and TRASH.as_posix().startswith('D:/FPS3D/FPSGAME/trash/')
entries = sorted(p for p in WORK.iterdir() if p.name not in KEEP)
rows = []
for top in entries:
    reason = REASONS.get(top.name, 'superseded iteration output (accepted final is r9)' if top.name.startswith('r')
                         else 'authoring log of an iteration round')
    files = [top] if top.is_file() else sorted(p for p in top.rglob('*') if p.is_file())
    for f in files:
        rel = f.relative_to(HERE)
        rows.append({'source': str(f).replace('\\', '/'), 'target': str(TRASH / rel).replace('\\', '/'),
                     'bytes': f.stat().st_size, 'sha256': sha(f), 'reason': reason})
RECEIPT.mkdir(parents=True, exist_ok=True)
manifest = {'task': 'runesword-guard-v24-20261122', 'accepted': 'user accepted r9 as the official guard, 2026-11-22',
            'replacement': {'final_review_sheets': 'F:/FPSGAMEData/ArtReviews/RuneSword20260913/GuardKuboldV24/20261122-r9',
                            'author_source': str(HERE).replace('\\', '/')},
            'files': rows, 'total_bytes': sum(r['bytes'] for r in rows), 'verified': False}
(RECEIPT / 'archive-manifest.json').write_text(json.dumps(manifest, indent=1), encoding='utf-8')
for top in entries:
    dest = TRASH / top.relative_to(HERE)
    dest.parent.mkdir(parents=True, exist_ok=True)
    shutil.move(str(top), str(dest))
bad = [r['target'] for r in rows if not Path(r['target']).is_file() or sha(r['target']) != r['sha256']]
gone = [r['source'] for r in rows if Path(r['source']).exists()]
if bad or gone:
    raise SystemExit('Archive verification failed: %d mismatched, %d still at source' % (len(bad), len(gone)))
manifest['verified'] = True
(RECEIPT / 'archive-manifest.json').write_text(json.dumps(manifest, indent=1), encoding='utf-8')
shutil.copy2(RECEIPT / 'archive-manifest.json', TRASH / 'archive-manifest.json')
print('ARCHIVED', len(rows), 'files', round(manifest['total_bytes'] / 2 ** 20, 1), 'MiB ->', TRASH)
