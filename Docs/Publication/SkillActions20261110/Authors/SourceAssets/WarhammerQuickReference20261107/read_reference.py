"""Measure the supplied video for authoring, excluding the hands and title."""
from pathlib import Path
import cv2
import json
import math
import numpy as np

P=Path(__file__).resolve().parent
cap=cv2.VideoCapture(str(P/'Reference/_5pAl232f38.mp4'))
START=55.65
FPS=60
TARGET_VERTICAL_FOV=75.
FOCAL_PIXELS=1080/(2*math.tan(math.radians(TARGET_VERTICAL_FOV/2)))
frames=[]
cap.set(cv2.CAP_PROP_POS_FRAMES,round(START*FPS))
for i in range(79):
    ok,frame=cap.read()
    if not ok:raise RuntimeError('Incomplete reference interval')
    frames.append(cv2.cvtColor(frame,cv2.COLOR_BGR2GRAY))
mask=np.zeros_like(frames[0]);mask[210:540,40:1300]=255;mask[540:1000,40:500]=255
origin=cv2.goodFeaturesToTrack(frames[0],maxCorners=1200,qualityLevel=.015,minDistance=12,mask=mask)
tracked=origin.copy()
rows=[]
for i,frame in enumerate(frames):
    if i:
        next_points,status,error=cv2.calcOpticalFlowPyrLK(frames[i-1],frame,tracked,None,winSize=(31,31),maxLevel=4)
        back,reverse_status,_=cv2.calcOpticalFlowPyrLK(frame,frames[i-1],next_points,None,winSize=(31,31),maxLevel=4)
        keep=(status[:,0]>0)&(reverse_status[:,0]>0)&(np.linalg.norm(back-tracked,axis=2)[:,0]<.8)
        origin=origin[keep];tracked=next_points[keep]
    a=origin[:,0];b=tracked[:,0]
    affine,inliers=cv2.estimateAffinePartial2D(a,b,method=cv2.RANSAC,ransacReprojThreshold=2.5)
    H=np.vstack([affine,[0,0,1]])
    points=np.float32([[[960,540],[1060,540],[960,640]]])
    q=cv2.perspectiveTransform(points,H)[0]
    shift=q[0]-points[0,0]
    roll=math.degrees(math.atan2(*(q[1]-q[0])[::-1]))
    # Reproduce normalized screen displacement at the game's default vertical
    # FOV. This does not require guessing the source camera's focal length.
    rows.append(dict(time=i/FPS,source=START+i/FPS,
        pitch=math.degrees(math.atan(shift[1]/FOCAL_PIXELS)),
        yaw=-math.degrees(math.atan(shift[0]/FOCAL_PIXELS)),roll=-roll,
        inliers=int(inliers.sum())))
# Remove the slight between-idle drift, then smooth one frame in either
# direction without smearing the source's short impact impulse.
for axis in ('pitch','yaw','roll'):
    raw=np.array([r[axis] for r in rows]);raw-=np.linspace(raw[0],raw[-1],len(raw))
    raw=np.convolve(np.pad(raw,(1,1),mode='edge'),[.2,.6,.2],mode='valid')
    for r,v in zip(rows,raw):r[axis]=float(v)
rows[0].update(pitch=0,yaw=0,roll=0);rows[-1].update(pitch=0,yaw=0,roll=0)
(P/'reference-camera.json').write_text(json.dumps(dict(url='https://www.youtube.com/watch?v=_5pAl232f38',
    requested=[54,57],active=[START,START+1.3],fps=FPS,target_vertical_fov=TARGET_VERTICAL_FOV,rows=rows),indent=2))
header=['#pragma once','#include "CoreMinimal.h"','',
    '// Static-background tracks: _5pAl232f38, 55.65-56.95 s. Generated by read_reference.py.',
    'namespace WarhammerQuickReferenceCamera','{','    struct FKey { float Pitch,Yaw,Roll; };',
    '    inline constexpr FKey Keys[]={']
header += ['        {%.7ff,%.7ff,%.7ff},'%(r['pitch'],r['yaw'],r['roll']) for r in rows]
header += ['    };','    inline FRotator Sample(float Seconds)','    {',
    '        const float Frame=FMath::Clamp(Seconds*60.f,0.f,float(UE_ARRAY_COUNT(Keys)-1));',
    '        const int32 I=FMath::Min(FMath::FloorToInt(Frame),int32(UE_ARRAY_COUNT(Keys))-2);',
    '        const auto& A=Keys[I];const auto& B=Keys[I+1];const float Alpha=Frame-I;',
    '        return FRotator(FMath::Lerp(A.Pitch,B.Pitch,Alpha),FMath::Lerp(A.Yaw,B.Yaw,Alpha),FMath::Lerp(A.Roll,B.Roll,Alpha));',
    '    }','}']
# Emitted alongside the measurements so a later source revision is reproducible.
(P/'WarhammerQuickReferenceCamera.generated.h').write_text('\n'.join(header)+'\n')
print('Reference camera authored', {a:[round(min(r[a] for r in rows),3),round(max(r[a] for r in rows),3)] for a in ('pitch','yaw','roll')})
