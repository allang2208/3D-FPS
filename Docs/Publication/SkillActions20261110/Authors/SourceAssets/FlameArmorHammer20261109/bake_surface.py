"""Read installed hammer meshes and bake bounded surface-triangle sampling data.
No asset edits, world simulation, preview or rendering.
"""
import bisect
import json
import math
import random
import zlib
from pathlib import Path
import unreal as u

ROOT = Path('D:/FPS3D/FPSGAME')
OUT = Path(__file__).resolve().parent
COUNT = 32
G, Q, L = u.GeometryScript_AssetUtils, u.GeometryScript_MeshQueries, u.GeometryScript_List


def paths(value):
    if isinstance(value, dict):
        for v in value.values():
            yield from paths(v)
    elif isinstance(value, list):
        for v in value:
            yield from paths(v)
    elif isinstance(value, str) and value.startswith('/Game/') and '/SM_' in value:
        yield value


def xyz(v):
    return (v.x, v.y, v.z)


def sub(a, b):
    return tuple(x-y for x, y in zip(a, b))


def cross(a, b):
    return (a[1]*b[2]-a[2]*b[1], a[2]*b[0]-a[0]*b[2], a[0]*b[1]-a[1]*b[0])


def bake(path):
    mesh = u.load_asset(path)
    if not isinstance(mesh, u.StaticMesh):
        raise RuntimeError('Missing hammer mesh: '+path)
    dm, outcome = G.copy_mesh_from_static_mesh(mesh, u.DynamicMesh(), u.GeometryScriptCopyMeshFromAssetOptions(),
        u.GeometryScriptMeshReadLOD(lod_type=u.GeometryScriptLODType.RENDER_DATA, lod_index=0))
    if outcome != u.GeometryScriptOutcomePins.SUCCESS:
        raise RuntimeError('Cannot read hammer triangles: '+path)
    _, vectors, _ = Q.get_all_vertex_positions(dm, False)
    _, faces, _ = Q.get_all_triangle_indices(dm, False)
    points = [xyz(p) for p in L.convert_vector_list_to_array(vectors)]
    faces = [(int(f.x), int(f.y), int(f.z)) for f in L.convert_triangle_list_to_array(faces)]
    low = [min(p[i] for p in points) for i in range(3)]
    high = [max(p[i] for p in points) for i in range(3)]
    center = [(a+b)*.5 for a, b in zip(low, high)]
    extent = [(b-a)*.5 for a, b in zip(low, high)]
    axis = 0 if extent[0] > extent[1] else 1
    triangles, cdf, total = [], [], 0.
    for tri_id, face in enumerate(faces):
        a, b, c = [points[i] for i in face]
        # Omit the small central mating region hidden inside the separate seat.
        station = ((a[axis]+b[axis]+c[axis])/3.-low[axis])/max(.001, high[axis]-low[axis])
        if .43 < station < .57:
            continue
        normal = cross(sub(b, a), sub(c, a))
        magnitude = math.sqrt(sum(v*v for v in normal))
        if magnitude < 1.e-6:
            continue
        total += magnitude*.5
        triangles.append((tri_id, a, b, c, [v/magnitude for v in normal]))
        cdf.append(total)
    if not triangles:
        raise RuntimeError('No exposed hammer head triangles: '+path)
    rng = random.Random(zlib.adler32(path.encode('utf-8')))
    patches = []
    for i in range(COUNT):
        target = total*(i+rng.uniform(.15,.85))/COUNT
        tri_id, a, b, c, normal = triangles[min(bisect.bisect_left(cdf, target), len(triangles)-1)]
        values = Q.get_triangle_normals(dm, tri_id)
        normals = [xyz(v) for v in values if isinstance(v, u.Vector)]
        if normals and sum(normal[j]*sum(n[j] for n in normals) for j in range(3)) < 0:
            normal = [-v for v in normal]
        patches.append(dict(a=a, b=b, c=c, normal=normal, triangle=tri_id))
    return dict(mesh=mesh.get_path_name(), center=center, extent=extent, axis=axis,
                total_triangles=len(faces), surface_area_cm2=total, patches=patches)


def vector(v):
    return 'FVector3f('+','.join(f'{x:.7f}f' for x in v)+')'


def run():
    meshes = set()
    for file in (ROOT/'Content/ColdSteelData').glob('*modules.json'):
        data = json.loads(file.read_text(encoding='utf-8-sig'))
        meshes.update(paths(data.get('slots', {}).get('hammer_heads', {})))
    if not meshes:
        raise RuntimeError('Hammer head catalog empty')
    rows = [bake(path) for path in sorted(meshes)]
    (OUT/'surface-data.json').write_text(json.dumps(rows, indent=2), encoding='utf-8')
    lines = ['// Generated by SourceAssets/FlameArmorHammer20261109/bake_surface.py.',
             'static const FProfile Profiles[] = {']
    for row in rows:
        lines.append('{TEXT("'+row['mesh']+'"),'+vector(row['center'])+','+vector(row['extent'])+','+str(row['axis'])+',{')
        for p in row['patches']:
            lines.append('{'+','.join(vector(p[k]) for k in ('a','b','c','normal'))+'},')
        lines.append('}},')
    lines.append('};')
    (ROOT/'Source/FPSGAME/Skills/HammerFireSurfaceData.inl').write_text('\n'.join(lines)+'\n', encoding='utf-8')
    print('HAMMER_SURFACE_BAKED', len(rows), 'meshes', COUNT, 'patches_per_mesh')


if __name__ == '__main__':
    run()
