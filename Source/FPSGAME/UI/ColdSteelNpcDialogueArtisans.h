struct FTopic
{
    const TCHAR* Title;
    const TCHAR* Reply;
    const TCHAR* FollowUp = nullptr;
    const TCHAR* FollowUpReply = nullptr;
};

struct FSpeaker
{
    static constexpr int32 TopicCount = 4;
    const TCHAR* Name;
    const TCHAR* Workshop;
    const TCHAR* Greeting;
    const TCHAR* TopicPrompt;
    const TCHAR* Lesson;
    FTopic Topics[TopicCount];
    const TCHAR* TradeLabel = TEXT("交易");
    const TCHAR* ChatLabel = TEXT("闲聊");
    const TCHAR* UnavailableLessonHint = nullptr;

    constexpr int32 MainChoiceCount() const { return (Lesson || UnavailableLessonHint) ? 3 : (TradeLabel ? 2 : 1); }
};

